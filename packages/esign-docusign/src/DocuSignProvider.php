/**
 * DocuSign eSignature REST API v2.1.
 *
 * Built from DocuSign's published documentation, not yet checked against a live account:
 * - Envelopes:create with status "sent" uploads the documents (base64), adds the signers with
 *   recipientId and routingOrder, places signHereTabs and sends the emails in one call.
 * - Envelopes:get with include=recipients gives the envelope status and each signer's status in
 *   one request. DocuSign allows one status GET per envelope per 15 minutes, so prefer Connect.
 * - "signed" is a short processing state before "completed". Only "completed" counts as Signed, and
 *   only then is documents/combined the finished PDF (it also answers for open envelopes, with
 *   the unsigned documents).
 * - "voided" covers both a sender's void and an expiry; voidedReason tells them apart.
 * - Envelopes:update with status "voided" and a voidedReason cancels an in-process envelope.
 * - Connect (JSON SIM) messages are verified with HMAC-SHA256 over the raw body, base64, in
 *   X-DocuSign-Signature-1..N. Connect only needs a 2xx back, so there is no custom webhook response.
 * - Reminders resend the envelope to one recipient (EnvelopeRecipients:update, resend_envelope=true).
 * - Expiry is moved through the envelope's notification settings (expirations.expireAfter, in days
 *   from the first send).
 * - Webhook management is left out: Connect configurations need an account admin, and their HMAC
 *   keys are generated by DocuSign in the admin UI, so a caller-chosen secret cannot be registered.
 */
final class DocuSignProvider implements SignatureProvider, HasCapabilities, ReportsSigners, SendsReminders, ExtendsExpiry, RecognizesWebhooks
{
    /** Connect JSON SIM events subscribed to for envelopes sent with a callbackUrl. */
    private const EVENTS = [
        'envelope-sent', 'envelope-delivered', 'envelope-completed', 'envelope-declined', 'envelope-voided',
        'recipient-completed', 'recipient-declined',
    ];

    /** Recipient statuses that mean "this signer has finished signing". */
    private const SIGNER_DONE = ['signed', 'completed', 'faxpending'];

    /** @var array<string, true> envelopes this instance has seen "completed"; completed is final */
    private array $completed = [];

    public function __construct(
        private readonly DocuSignApi $api,
        private readonly DocuSignOptions $options = new DocuSignOptions(),
    ) {
    }

    public function name(): string
    {
        return 'docusign';
    }

    public function capabilities(): Capabilities
    {
        return new Capabilities(
            // SMS needs the account's Phone Authentication workflow, so it is only on when configured.
            identityMethods: $this->options->phoneAuthWorkflowId === null ? [IdentityMethod::Email] : [IdentityMethod::Email, IdentityMethod::SmsOtp],
            features: [
                Feature::MultipleDocuments, Feature::SigningOrder, Feature::FieldPlacement,
                Feature::Reminders, Feature::ExpiryExtension, Feature::SignerDetails,
            ],
            // Signers are remote: DocuSign emails the links. Embedded signing (clientUserId) would
            // suppress those emails, so send() returns no signing URLs.
        );
    }

    public function details(string $envelopeId): EnvelopeDetails
    {
        $data = $this->envelope($envelopeId);
        $status = $this->remember($envelopeId, $this->map($data));

        $signers = array_map(fn (array $s) => new SignerState(
            (string) ($s['email'] ?? ''),
            (string) ($s['name'] ?? ''),
            match (strtolower((string) ($s['status'] ?? ''))) {
                'signed', 'completed', 'faxpending' => SignerStatus::Signed,
                'declined' => SignerStatus::Declined,
                // created, sent, delivered, autoresponded: not acted yet
                default => SignerStatus::Pending,
            },
            null,
            is_numeric($s['routingOrder'] ?? null) ? (int) $s['routingOrder'] : null,
        ), self::signers($data));

        return new EnvelopeDetails(new EnvelopeRef('docusign', $envelopeId), $status, $signers);
    }

    public function send(Envelope $envelope): SentEnvelope
    {
        // Everything is validated before the first HTTP call, token included.
        if (mb_strlen($envelope->subject) > 100) {
            throw new EsignException('DocuSign limits the email subject to 100 characters.');
        }
        $documents = array_map(fn (Document $d, int $i) => $this->document($d, $i), $envelope->documents, array_keys($envelope->documents));
        $signers = [];
        foreach (array_values($envelope->signers) as $i => $signer) {
            $signers[] = $this->signer($signer, (string) ($i + 1), count($documents));
        }

        $body = [
            'emailSubject' => $envelope->subject,
            'documents' => $documents,
            'recipients' => ['signers' => $signers],
            'status' => 'sent',
        ];
        if ($envelope->message !== '') {
            $body['emailBlurb'] = $envelope->message;
        }
        if ($envelope->metadata !== []) {
            $body['customFields'] = ['textCustomFields' => $this->customFields($envelope->metadata)];
        }
        if ($envelope->callbackUrl !== null) {
            $body['eventNotification'] = [
                'url' => $envelope->callbackUrl,
                'requireAcknowledgment' => 'true',
                'deliveryMode' => 'SIM',
                'events' => self::EVENTS,
                'eventData' => ['version' => 'restv2.1'],
                // Needs HMAC enabled on the account (Connect settings). parseWebhook() refuses unsigned messages.
                'includeHMAC' => 'true',
            ];
        }

        $created = $this->api->post('/envelopes', $body);
        $envelopeId = $created['envelopeId'] ?? null;
        if (! is_string($envelopeId) || $envelopeId === '') {
            throw new ProviderError('docusign', 'Envelope was created without an envelopeId.');
        }

        // Signers are remote (no clientUserId): DocuSign emails each one a link, so there are no URLs to return.
        return new SentEnvelope('docusign', $envelopeId, EnvelopeStatus::Sent);
    }

    public function status(string $envelopeId): EnvelopeStatus
    {
        return $this->remember($envelopeId, $this->map($this->envelope($envelopeId)));
    }

    public function download(string $envelopeId): string
    {
        if (! isset($this->completed[$envelopeId])) {
            // Reuse a "completed" seen by status() in this process: it is final, and DocuSign limits status GETs.
            $status = $this->map($this->envelope($envelopeId));
            if ($status !== EnvelopeStatus::Signed) {
                throw new EsignException("DocuSign envelope {$envelopeId} is {$status->value}, not signed. There is no signed PDF yet.");
            }
        }

        $pdf = $this->api->file('/envelopes/' . rawurlencode($envelopeId) . '/documents/combined');
        if (! str_starts_with($pdf, '%PDF')) {
            throw new ProviderError('docusign', "DocuSign returned something other than a PDF for envelope {$envelopeId}.");
        }

        return $pdf;
    }

    /** Voids the envelope. DocuSign refuses (ENVELOPE_CANNOT_VOID_INVALID_STATE) once it is completed or voided. */
    public function cancel(string $envelopeId): void
    {
        $this->void($envelopeId, $this->options->voidReason);
    }

    /** Connect signs every call with X-DocuSign-Signature-1 (HMAC must be on, which this driver requires). */
    public function recognizesWebhook(array $headers, string $rawBody): bool
    {
        return Headers::has($headers, 'X-DocuSign-Signature-1');
    }

    public function parseWebhook(array $headers, string $rawBody): WebhookEvent
    {
        $secrets = $this->options->webhookSecrets;
        if ($secrets === []) {
            throw new InvalidWebhook('No DocuSign webhook_secret is configured, so Connect messages cannot be verified. Refusing the webhook.');
        }

        $signatures = [];
        foreach ($headers as $name => $values) {
            if (preg_match('/^x-docusign-signature-\d+$/i', (string) $name)) {
                foreach ((array) $values as $value) {
                    $signatures[] = trim((string) $value);
                }
            }
        }
        if ($signatures === []) {
            throw new InvalidWebhook('DocuSign webhook has no X-DocuSign-Signature header. Is HMAC enabled for this Connect configuration?');
        }

        // One match is enough: DocuSign adds one header per HMAC key on the account.
        $valid = false;
        foreach ($secrets as $secret) {
            $expected = base64_encode(hash_hmac('sha256', $rawBody, $secret, true));
            foreach ($signatures as $signature) {
                $valid = hash_equals($expected, $signature) || $valid;
            }
        }
        if (! $valid) {
            throw new InvalidWebhook('DocuSign webhook signature does not match.');
        }

        $payload = json_decode($rawBody, true);
        if (! is_array($payload)) {
            throw new InvalidWebhook('DocuSign webhook body is not JSON. Set the Connect configuration to JSON (SIM, restv2.1).');
        }
        $id = is_array($payload['data'] ?? null) ? ($payload['data']['envelopeId'] ?? null) : null;
        if (! is_string($id) || $id === '') {
            throw new InvalidWebhook('DocuSign webhook has no data.envelopeId.');
        }

        /** @var array<string, mixed> $payload */
        return new WebhookEvent('docusign', $id, null, $payload);
    }

    // ---- DocuSign-only operations ------------------------------------------------

    /** Void with your own reason (DocuSign keeps the first 200 characters). */
    public function void(string $envelopeId, string $reason): void
    {
        if (trim($reason) === '') {
            throw new EsignException('DocuSign needs a reason to void an envelope.');
        }
        $this->api->put('/envelopes/' . rawurlencode($envelopeId), ['status' => 'voided', 'voidedReason' => $reason]);
    }

    /**
     * Resend the envelope to a signer who hasn't signed yet: EnvelopeRecipients:update with
     * resend_envelope=true and only the recipientId, because sending the email again would be
     * treated as an address correction.
     */
    public function remind(string $envelopeId, string $signerEmail): void
    {
        $path = '/envelopes/' . rawurlencode($envelopeId) . '/recipients';
        $matches = array_filter(self::signers(['recipients' => $this->api->get($path)]), fn (array $s) => strcasecmp((string) ($s['email'] ?? ''), $signerEmail) === 0);
        if ($matches === []) {
            throw new EsignException("{$signerEmail} is not a signer of DocuSign envelope {$envelopeId}.");
        }
        $pending = array_filter($matches, fn (array $s) => ! in_array(strtolower((string) ($s['status'] ?? '')), [...self::SIGNER_DONE, 'declined'], true));
        if ($pending === []) {
            throw new EsignException("{$signerEmail} has already acted on DocuSign envelope {$envelopeId}; there is nothing to remind.");
        }

        $summary = $this->api->put($path, [
            'signers' => array_values(array_map(fn (array $s) => ['recipientId' => (string) ($s['recipientId'] ?? '')], $pending)),
        ], ['resend_envelope' => 'true']);

        // A recipient that cannot be updated still comes back as HTTP 200, with errorDetails per recipient.
        foreach (is_array($summary['recipientUpdateResults'] ?? null) ? $summary['recipientUpdateResults'] : [] as $result) {
            $code = is_array($result) && is_array($result['errorDetails'] ?? null) ? ($result['errorDetails']['errorCode'] ?? null) : null;
            if (is_string($code) && $code !== '' && $code !== 'SUCCESS') {
                $message = is_string($result['errorDetails']['message'] ?? null) ? $result['errorDetails']['message'] : 'Recipient could not be updated';
                throw new ProviderError('docusign', "PUT /envelopes/{$envelopeId}/recipients: {$message}", 200, $code);
            }
        }
    }

    /**
     * DocuSign counts expiry in whole days from the envelope's first send (expirations.expireAfter),
     * so the new deadline is rounded up to the next whole day: the envelope stays open at least
     * until $until. The current reminder and warning settings are read first and sent back
     * unchanged, so moving the deadline doesn't reset them.
     */
    public function extend(string $envelopeId, DateTimeInterface $until): void
    {
        if ($until <= new DateTimeImmutable()) {
            throw new EsignException('The new DocuSign deadline must be in the future.');
        }
        $envelope = $this->api->get('/envelopes/' . rawurlencode($envelopeId));
        $sentAt = is_string($envelope['initialSentDateTime'] ?? null) ? self::date($envelope['initialSentDateTime']) : null;
        if ($sentAt === null) {
            throw new ProviderError('docusign', "DocuSign envelope {$envelopeId} has no initialSentDateTime; only a sent envelope can be extended.");
        }
        $days = (int) ceil(($until->getTimestamp() - $sentAt->getTimestamp()) / 86400);

        $path = '/envelopes/' . rawurlencode($envelopeId) . '/notification';
        $current = $this->api->get($path);
        $expirations = ['expireEnabled' => 'true', 'expireAfter' => (string) max(1, $days)];
        $warn = is_array($current['expirations'] ?? null) ? ($current['expirations']['expireWarn'] ?? null) : null;
        if (is_string($warn) || is_int($warn)) {
            $expirations['expireWarn'] = (string) $warn;
        }
        $body = ['useAccountDefaults' => 'false', 'expirations' => $expirations];
        if (is_array($current['reminders'] ?? null)) {
            $body['reminders'] = $current['reminders'];
        }

        $this->api->put($path, $body);
    }

    // ---- internals ------------------------------------------------------------------

    private function remember(string $envelopeId, EnvelopeStatus $status): EnvelopeStatus
    {
        if ($status === EnvelopeStatus::Signed) {
            $this->completed[$envelopeId] = true;
        }

        return $status;
    }

    /**
     * The signers from an envelope (include=recipients) or a recipients list.
     *
     * @param array<string, mixed> $data
     *
     * @return list<array<string, mixed>>
     */
    private static function signers(array $data): array
    {
        $recipients = is_array($data['recipients'] ?? null) ? $data['recipients'] : [];
        $signers = is_array($recipients['signers'] ?? null) ? $recipients['signers'] : [];

        /** @var list<array<string, mixed>> */
        return array_values(array_filter($signers, 'is_array'));
    }

    private static function date(string $value): ?DateTimeImmutable
    {
        // DocuSign writes 7 fractional digits ("2026-10-18T10:00:00.0000000Z"); PHP reads at most 6.
        $normalized = (string) preg_replace('/(\.\d{6})\d+/', '$1', $value);
        try {
            return new DateTimeImmutable($normalized);
        } catch (\Exception) {
            return null;
        }
    }

    /** @return array<string, string> */
    private function document(Document $document, int $index): array
    {
        $extension = $document->mimeType === 'application/pdf' ? 'pdf' : strtolower(pathinfo($document->name, PATHINFO_EXTENSION));
        if ($extension === '') {
            // DocuSign converts non-PDF documents but needs the file extension to do it.
            throw new EsignException("Document \"{$document->name}\" is {$document->mimeType} and has no file extension; DocuSign needs one to convert it.");
        }

        return [
            'documentId' => (string) ($index + 1),
            'name' => $document->name,
            'fileExtension' => $extension,
            'documentBase64' => base64_encode($document->contents),
        ];
    }

    /** @return array<string, mixed> */
    private function signer(Signer $signer, string $recipientId, int $documentCount): array
    {
        $recipient = [
            'recipientId' => $recipientId,
            'routingOrder' => (string) max(1, $signer->order),
            'name' => $signer->name,
            'email' => $signer->email,
        ];

        if ($signer->identity === IdentityMethod::SmsOtp) {
            $recipient['identityVerification'] = $this->phoneAuthentication($signer);
        } elseif ($signer->identity !== IdentityMethod::Email) {
            throw new EsignException("DocuSign does not support the \"{$signer->identity->value}\" identity method. Use email or sms_otp.");
        }

        $tabs = [];
        foreach ($signer->fields as $field) {
            $tabs[] = $this->signHere($signer, $field, $recipientId, $documentCount);
        }
        if ($tabs !== []) {
            $recipient['tabs'] = ['signHereTabs' => $tabs];
        }

        return $recipient;
    }

    /**
     * Phone authentication, as in DocuSign's "require phone authentication" how-to: the account's
     * Phone Authentication workflow plus the number, split into country code and national number.
     * The recipient then chooses between a text message and a call.
     *
     * @return array<string, mixed>
     */
    private function phoneAuthentication(Signer $signer): array
    {
        if ($this->options->phoneAuthWorkflowId === null) {
            throw new EsignException('DocuSign SMS authentication needs phone_auth_workflow_id: the account\'s "Phone Authentication" workflow ID.');
        }
        // DocuSign wants countryCode and number separately. Splitting a bare E.164 number needs a
        // numbering-plan table, so a separator after the country code is required instead of a guess.
        if (! preg_match('/^\+?(\d{1,3})[\s.-]+([\d\s.-]{4,20})$/', trim((string) $signer->mobile), $m)) {
            throw new EsignException("Signer \"{$signer->name}\" needs a mobile number like \"+966 501234567\" (country code, a space, then the number) for DocuSign SMS authentication.");
        }

        return [
            'workflowId' => $this->options->phoneAuthWorkflowId,
            'inputOptions' => [[
                'name' => 'phone_number_list',
                'valueType' => 'PhoneNumberList',
                'phoneNumberList' => [['countryCode' => $m[1], 'number' => (string) preg_replace('/\D/', '', $m[2])]],
            ]],
        ];
    }

    /**
     * SignatureField is in PDF points from the top-left; DocuSign positions tabs at 72 DPI from the
     * top-left, which is the same unit. width and height do not apply to Sign Here tabs and are not sent.
     *
     * @return array<string, string>
     */
    private function signHere(Signer $signer, SignatureField $field, string $recipientId, int $documentCount): array
    {
        if ($field->documentIndex < 0 || $field->documentIndex >= $documentCount) {
            throw new EsignException("Signer \"{$signer->name}\" has a field on document {$field->documentIndex}, but the envelope has {$documentCount} document(s).");
        }

        return [
            'documentId' => (string) ($field->documentIndex + 1),
            'recipientId' => $recipientId,
            'pageNumber' => (string) max(1, $field->page),
            'xPosition' => (string) (int) round($field->x),
            'yPosition' => (string) (int) round($field->y),
        ];
    }

    /**
     * @param array<string, string> $metadata
     *
     * @return list<array<string, string>>
     */
    private function customFields(array $metadata): array
    {
        $fields = [];
        foreach ($metadata as $name => $value) {
            if (mb_strlen((string) $value) > 100) {
                throw new EsignException("Metadata \"{$name}\" is longer than the 100 characters a DocuSign custom field holds.");
            }
            $fields[] = ['name' => (string) $name, 'value' => (string) $value, 'show' => 'false'];
        }

        return $fields;
    }

    /** @return array<string, mixed> */
    private function envelope(string $envelopeId): array
    {
        return $this->api->get('/envelopes/' . rawurlencode($envelopeId), ['include' => 'recipients']);
    }

    /**
     * DocuSign envelope status → EnvelopeStatus. See the README for the table.
     *
     * @param array<string, mixed> $data
     */
    private function map(array $data): EnvelopeStatus
    {
        $raw = is_string($data['status'] ?? null) ? $data['status'] : '';

        return match (strtolower(trim($raw))) {
            'completed' => EnvelopeStatus::Signed,
            // Everyone signed and DocuSign is still finishing the envelope. Not final: the signed
            // PDF is only certain once it moves to "completed".
            'signed' => EnvelopeStatus::PartiallySigned,
            'declined' => EnvelopeStatus::Declined,
            'voided' => $this->expired($data) ? EnvelopeStatus::Expired : EnvelopeStatus::Cancelled,
            'timedout' => EnvelopeStatus::Expired,      // legacy, no longer used by DocuSign
            'deleted' => EnvelopeStatus::Cancelled,     // legacy, no longer used by DocuSign
            // "correct": the sender opened it for correction and signing is paused, but it is not over.
            'created', 'sent', 'delivered', 'correct' => $this->anyoneSigned($data) ? EnvelopeStatus::PartiallySigned : EnvelopeStatus::Sent,
            default => throw new ProviderError('docusign', "DocuSign returned an envelope status this driver does not know: \"{$raw}\". Please report it."),
        };
    }

    /**
     * DocuSign reports expiry as "voided" and says the voidedReason tells the two apart, without
     * documenting the exact text. Only a reason that mentions expiry counts; anything else is a cancel.
     *
     * @param array<string, mixed> $data
     */
    private function expired(array $data): bool
    {
        $reason = is_string($data['voidedReason'] ?? null) ? $data['voidedReason'] : '';

        return (bool) preg_match('/\bexpir(ed|y|ation)\b/i', $reason);
    }

    /** @param array<string, mixed> $data */
    private function anyoneSigned(array $data): bool
    {
        foreach (self::signers($data) as $signer) {
            if (in_array(strtolower((string) ($signer['status'] ?? '')), self::SIGNER_DONE, true)) {
                return true;
            }
        }

        return false;
    }
}
